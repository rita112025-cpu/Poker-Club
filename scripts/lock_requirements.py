"""Pin the installed Python dependency graph after a deliberate dependency update.

Run with .venv Python after installing backend[dev]. Extras are expanded using
the generating platform; the lock lists concrete packages without extras so
Linux uses uvicorn's portable loop instead of adding an unpinned uvloop.
Revalidate both target platforms after updates. No package index secrets emitted.
"""

from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name


def resolve(roots: list[str]) -> list[str]:
    pending = [Requirement(root) for root in roots]
    visited: set[tuple[str, tuple[str, ...]]] = set()
    pins: dict[str, str] = {}
    while pending:
        requirement = pending.pop()
        name = canonicalize_name(requirement.name)
        extras = tuple(sorted(requirement.extras))
        if (name, extras) in visited:
            continue
        visited.add((name, extras))
        distribution = metadata.distribution(name)
        pins[name] = distribution.version
        for raw in distribution.requires or []:
            dependency = Requirement(raw)
            if dependency.marker is None or any(
                dependency.marker.evaluate({"extra": extra}) for extra in ("", *extras)
            ):
                pending.append(dependency)
    return [f"{name}=={version}" for name, version in sorted(pins.items())]


def main() -> None:
    project = metadata.distribution("poker-club-backend")
    runtime = [raw for raw in project.requires or [] if Requirement(raw).marker is None]
    dev = [
        raw
        for raw in project.requires or []
        if Requirement(raw).marker is not None
        and Requirement(raw).marker.evaluate({"extra": "dev"})  # type: ignore[union-attr]
    ]
    root = Path(__file__).resolve().parents[1] / "backend"
    for filename, requirements in [
        ("requirements.lock", runtime),
        ("requirements-dev.lock", runtime + dev),
    ]:
        (root / filename).write_text(
            "# Generated by scripts/lock_requirements.py; Python 3.12, Windows.\n"
            "# Exact portable package pins; regenerate deliberately, then run checks.\n"
            + "\n".join(resolve(requirements))
            + "\n",
            encoding="utf-8",
        )


if __name__ == "__main__":
    main()
